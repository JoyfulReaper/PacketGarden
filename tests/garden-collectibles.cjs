// Exact-specimen mutation/collection checks: production scripts, injected time/rolls, no sleeps.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const createGarden = require('./browser-garden.cjs');
const activeCount = garden => garden.run('gardenState.specimens.filter(specimen=>specimen.mutation).length');
const center = specimen => [(specimen.column + 0.5) * 30, (specimen.row + 0.5) * 30];
const activate = garden => { garden.clock.now += 3000; garden.tick(); };

const garden = createGarden(), { run, element, clock } = garden;
assert.equal(garden.sources.length, 1);
assert.equal(garden.sources[0].handlers.get('garden').length, 1);
assert.equal(garden.intervals.length, 2, 'only existing garden/inspection timers');
assert.equal(element('canvas').handlers.get('click').length, 1);
assert.equal(element('#garden-score').textContent, 'Score: 0');
assert.equal(run('specimenMutationConfig.port22WeedChance'), 0.05);
assert.equal(run('specimenMutationConfig.mutationDelayMs'), 3000);
assert.equal(run('specimenMutationConfig.collectibleLifetimeMs'), 20000);
assert.equal(run('specimenMutationConfig.maxActive'), 3);
assert.equal(run('typeof maybeSpawnPort22Collectible'), 'undefined', 'old sprig producer removed');
assert.equal(run('Object.hasOwn(gardenState,"collectibles")'), false, 'no unused loose-drop state');

const initialGrass = run('JSON.stringify(gardenState.grassCells)');
garden.forceRoll(0.049999); garden.emit();
const source = run('gardenState.specimens[0]');
const grassBefore = JSON.stringify(JSON.parse(initialGrass).filter(g=>g.column!==source.column||g.row!==source.row));
const originalCell = JSON.stringify([source.column, source.row]);
const originalOrigin = JSON.stringify(source.origin), originalColor = source.colorVariant;
const originalRecent = run('JSON.stringify(gardenState.recentEvents)');
assert.equal(source.type, 'redbloom'); assert.equal(source.mutation, undefined);
assert.equal(source.pendingMutation.type, 'collectible_weed');
assert.equal(source.pendingMutation.activateAt, source.createdAt + 3000);
assert.equal(run('drawSpecimenMutation(gardenState.specimens[0],Date.now())'), false, 'initial normal redbloom rendering');
assert.equal(run('gardenState.specimens.length'), 1);
assert.equal(run('JSON.stringify(gardenState.grassCells)'), grassBefore);
garden.click(...center(source));
assert.equal(element('#specimen-card').hidden, false, 'normal redbloom click inspects');
assert.equal(element('#specimen-mutation').textContent, 'None');
clock.now += 2999; garden.tick();
assert.equal(source.mutation, undefined, 'redbloom remains visible throughout delay');
clock.now++; garden.tick();
assert.equal(run('gardenState.specimens[0]'), source, 'the exact same specimen mutates');
assert.equal(source.pendingMutation, undefined);
assert.deepEqual(Object.keys(source.mutation).sort(), ['createdAt', 'expiresAt', 'type']);
assert.equal(source.mutation.type, 'collectible_weed');
assert.equal(source.mutation.createdAt, clock.now);
assert.equal(source.mutation.expiresAt, clock.now + 20000);
assert.equal(source.type, 'redbloom'); assert.equal(source.vigor, 0);
assert.equal(source.colorVariant, originalColor);
assert.equal(JSON.stringify(source.origin), originalOrigin);
assert.equal(JSON.stringify([source.column, source.row]), originalCell);
assert.equal(run('gardenState.specimens.length'), 1, 'no extra specimen or cell');
assert.equal(run('JSON.stringify(gardenState.grassCells)'), grassBefore);
assert.equal(run('JSON.stringify(gardenState.recentEvents)'), originalRecent, 'no mutation row or event rewrite');
assert(element('#recent-event-0').textContent.includes(':22 · redbloom · seen 12'));
assert.match(element('#garden-status').textContent, /1 red bloom, 0 weeds/);
garden.intervals.find(interval => interval.delay === 1000).handler();
assert.equal(element('#specimen-mutation').textContent, 'Collectible weed');
assert.equal(element('#specimen-sensor').textContent, 'garden-test');
assert.equal(element('#specimen-port').textContent, '22');
assert.equal(element('#specimen-seen-count').textContent, '12');

// Scaled cell routing: outside the plant inspects; the mutation itself collects.
garden.resize({ left: 130, top: 105, width: 390, height: 740 });
const [x, y] = center(source);
garden.click(x + 14, y + 14);
assert.equal(run('gardenState.specimens[0]'), source, 'outside the plant does not collect');
assert.equal(element('#specimen-card').hidden, false);
let collectionSounds = 0;
garden.sandbox.collectionSound = () => collectionSounds++;
run('gardenSound.maybePlayCollectionSound=collectionSound');
garden.click(x, y);
assert.equal(run('gardenState.specimens.length'), 0, 'collect removes exact specimen');
assert.equal(element('#specimen-card').hidden, true, 'its inspection card closes immediately');
assert.equal(run('inspectedSpecimen'), null);
assert.equal(collectionSounds, 1, 'existing collection sound path reused');
assert.match(element('#garden-status').textContent, /0 red blooms/);
assert.equal(element('#collection-message').textContent, 'You collected some weed. +0 points');
assert.equal(element('#collection-message').hidden, false);
assert.equal(element('#garden-score').textContent, 'Score: 0');
assert.equal(run('JSON.stringify(gardenState.recentEvents)'), originalRecent);
assert.equal(run('collectSpecimenMutation(undefined)'), false);
garden.sandbox.collectedSource = source;
assert.equal(run('collectSpecimenMutation(collectedSource)'), false, 'no duplicate collection');
clock.now += 1999; garden.tick(); assert.equal(element('#collection-message').hidden, false);
clock.now++; garden.tick(); assert.equal(element('#collection-message').hidden, true);
assert.equal(element('#collection-message').textContent, '');
garden.click(x, y); assert.equal(element('#specimen-card').hidden, true, 'empty soil closes inspection');

const failed = createGarden(); failed.forceRoll(0.05); failed.emit();
assert.equal(failed.run('gardenState.specimens[0].pendingMutation'), undefined, '5% boundary excluded');
activate(failed); assert.equal(activeCount(failed), 0);
assert.equal(failed.run('gardenState.specimens.length'), 1);
failed.forceRoll(0);
for (const [port, type] of [[2222, 'redbloom'], [443, 'flower'], [22, 'weed']]) failed.emit(port, type);
failed.element('#fake-port22-probe').handlers.get('click')[0]();
assert.equal(failed.run('gardenState.specimens.filter(specimen=>specimen.pendingMutation).length'), 0, 'only successful live port-22 redbloom schedules');
assert.equal(failed.run('scheduleSpecimenMutation(gardenState.specimens[0],"unimplemented")'), false);
assert.equal(failed.run('maybeSchedulePort22Mutation({type:"redbloom"},0)'), false, 'detached source cannot schedule');

const full = createGarden(); full.forceRoll(0); full.fill(3); full.emit(); full.emit(22, 'redbloom', 3);
activate(full); assert.equal(activeCount(full), 0, 'dropped saturated growth cannot mutate');
full.fill(0); full.emit(22, 'redbloom', 3);
const replacement = full.run('gardenState.specimens[0]');
assert(replacement.pendingMutation); assert.equal(replacement.column, 0); assert.equal(replacement.row, 0);
activate(full); assert.equal(full.run('gardenState.specimens.length'), 640);
assert.equal(full.run('gardenState.specimens[0]'), replacement);
assert.equal(replacement.type, 'redbloom'); assert.equal(activeCount(full), 1);
// The canonical redbloom remains subject to the same vigor displacement rule.
full.run('gardenState.specimens.forEach(specimen=>specimen.vigor=3); gardenState.specimens[0].vigor=0'); full.emit(443, 'flower', 3);
assert.equal(full.run('gardenState.specimens[0].type'), 'flower');
assert.equal(activeCount(full), 0);

const displaced = createGarden(); displaced.forceRoll(0); displaced.fill(0); displaced.emit(22, 'redbloom', 1);
displaced.run('gardenState.specimens.slice(1).forEach(specimen=>specimen.vigor=3)');
const lost = displaced.run('gardenState.specimens[0]');
displaced.sandbox.lostSource = lost;
displaced.emit(443, 'flower', 3); activate(displaced);
assert.equal(lost.mutation, undefined, 'displaced pending source never mutates');
assert.equal(displaced.run('activateSpecimenMutation(lostSource)'), false);
assert.equal(activeCount(displaced), 0);
const expired = createGarden(); expired.forceRoll(0); expired.emit();
const old = expired.run('gardenState.specimens[0]');
expired.clock.now += 30000; expired.tick();
assert.equal(expired.run('gardenState.specimens.length'), 0);
assert.equal(old.mutation, undefined, 'expired source cannot activate after a paused tick');

const capped = createGarden(); capped.forceRoll(0);
capped.run('spawnSpecimen("weed"); spawnSpecimen("weed"); spawnSpecimen("weed")');
for (let i = 0; i < 4; i++) capped.emit();
assert.equal(capped.run('gardenState.specimens.filter(specimen=>specimen.pendingMutation).length'), 4);
activate(capped); assert.equal(activeCount(capped), 3);
const skipped = capped.run('gardenState.specimens.filter(specimen=>specimen.type==="redbloom")[3]');
assert.equal(skipped.mutation, undefined); assert.equal(skipped.pendingMutation, undefined);
const collected = capped.run('gardenState.specimens.find(specimen=>specimen.mutation)'); capped.click(...center(collected));
capped.tick(); assert.equal(activeCount(capped), 2, 'cap-skipped candidate never catches up');
assert.equal(skipped.mutation, undefined); assert.equal(skipped.type, 'redbloom');
assert.equal(capped.element('#garden-score').textContent, 'Score: 0');

const lifetime = createGarden(); lifetime.forceRoll(0); lifetime.emit(); activate(lifetime);
const temporary = lifetime.run('gardenState.specimens[0]');
lifetime.clock.now += 19999; lifetime.tick(); assert.equal(lifetime.run('gardenState.specimens[0]'), temporary);
lifetime.clock.now++; lifetime.tick(); assert.equal(lifetime.run('gardenState.specimens.length'), 0);
assert.equal(lifetime.element('#collection-message').hidden, true, 'silent expiry, no missed message');
assert.equal(lifetime.run('drawSpecimenMutation({mutation:{type:"collectible_weed",expiresAt:Date.now()}},Date.now())'), true, 'no expired redbloom flash');
// A late activation still has a full 20-second window; ordinary species timing is unchanged.
const late = createGarden(); late.forceRoll(0); late.emit(); late.clock.now += 29000; late.tick();
assert.equal(activeCount(late), 1);
late.clock.now += 19999; late.tick(); assert.equal(late.run('gardenState.specimens.length'), 1);
late.clock.now++; late.tick(); assert.equal(late.run('gardenState.specimens.length'), 0);
const ordinary = createGarden(); ordinary.emit(22, 'weed');
const ordinaryWeed = ordinary.run('gardenState.specimens[0]');
assert.equal(ordinaryWeed.pendingMutation, undefined);
const weedLifetime = ordinary.run('speciesConfig.get("weed").timings.expiredAfterMs');
assert(weedLifetime > 30000);
ordinary.clock.now += 30000; ordinary.tick(); assert.equal(ordinary.run('gardenState.specimens[0]'), ordinaryWeed);
ordinary.clock.now = ordinaryWeed.createdAt + weedLifetime; ordinary.tick(); assert.equal(ordinary.run('gardenState.specimens.length'), 0);

const repeated = createGarden(); repeated.forceRoll(0);
for (let i = 0; i < 3; i++) {
  repeated.emit(); activate(repeated);
  repeated.click(...center(repeated.run('gardenState.specimens[0]')));
  assert.equal(repeated.run('gardenState.specimens.length'), 0);
  assert.equal(repeated.element('#garden-score').textContent, 'Score: 0');
  assert.equal(repeated.element('#collection-message').textContent, 'You collected some weed. +0 points');
}
assert.equal(repeated.audioContexts(), 0, 'Sound Off never creates an AudioContext');
assert(!Object.keys(repeated.run('gardenState')).some(key => /score|inventory|points|collected/i.test(key)), 'no scoring/inventory counters');
const scripts = [...fs.readFileSync('wwwroot/canvas.html', 'utf8').matchAll(/<script src="([^"]+)" defer><\/script>/g)];
for (const [, file] of scripts) assert(!/localStorage|sessionStorage|garden-score/.test(fs.readFileSync('wwwroot/' + file.split('?')[0], 'utf8')), 'static score has no JavaScript updater or persistence');

const gnomes = createGarden(); gnomes.fill(0); gnomes.forceRoll(0); gnomes.emit(22, 'redbloom', 3);
const actorState = () => gnomes.run('JSON.stringify([gardenState.actors,gnomeIncident])');
gnomes.run('startGnomeIncident(Date.now(),()=>0.5)');
let actors = actorState();
gnomes.run('updateGarden(Date.now()+3000)'); assert.equal(actorState(), actors, 'activation leaves gnomes alone');
gnomes.run('finishGnomeIncident()'); assert.equal(activeCount(gnomes), 1, 'gnome cleanup preserves mutation');
gnomes.run('startGnomeIncident(Date.now(),()=>0.5)'); actors = actorState();
gnomes.run('collectSpecimenMutation(gardenState.specimens[0])'); assert.equal(actorState(), actors, 'collection leaves gnomes alone');
gnomes.emit(22, 'redbloom', 3); gnomes.run('updateGarden(Date.now()+3000)'); actors = actorState();
gnomes.run('updateGarden(Date.now()+23000)'); assert.equal(actorState(), actors, 'expiry leaves gnomes alone');

const rendered = createGarden(); rendered.forceRoll(0); rendered.emit();
const renderCell = center(rendered.run('gardenState.specimens[0]')); activate(rendered);
rendered.drawing.length = 0; rendered.run('drawSpecimenMutation(gardenState.specimens[0],Date.now())');
assert(rendered.drawing.some(([method, x, y]) => method === 'translate' && x === renderCell[0] && y === renderCell[1]));
assert.equal(rendered.drawing.filter(([method]) => method === 'ellipse').length, 3, 'rooted paired leaves');
assert(rendered.drawing.filter(([method]) => method === 'ellipse').every(args => args.length === 8 && args[7] === Math.PI * 2), 'complete leaf paths');
assert.equal(rendered.drawing.filter(([method]) => method === 'save').length, rendered.drawing.filter(([method]) => method === 'restore').length);
assert(rendered.drawing.every(([, ...args]) => args.every(value => typeof value !== 'number' || Number.isFinite(value))));
const layers = []; rendered.sandbox.mark = layer => layers.push(layer);
rendered.run('gardenState.grassCells=[{column:0,row:0,createdAt:Date.now(),lastInfluencedAt:Date.now()}]; drawGrass=()=>mark("grass"); drawCollectibleWeed=()=>mark("mutation"); specimenMutationTypes.get("collectible_weed").render=drawCollectibleWeed; speciesConfig.get("redbloom").render=()=>mark("redbloom"); drawGardenActors=()=>mark("actor"); drawRain=()=>mark("weather"); drawGarden()');
assert.deepEqual(layers, ['grass', 'mutation', 'actor', 'weather'], 'mutation replaces only canonical specimen drawing');

console.log('PASS: delayed exact-redbloom mutations, provenance/cell/type preservation, cap/no retry, saturation/displacement/expiry, scaled collection/inspection, +0/static score, Recent activity, ordinary weeds, gnomes, and muted shared audio.');
